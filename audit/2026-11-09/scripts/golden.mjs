import { createRequire } from 'module'; const { chromium, devices } = createRequire(import.meta.url)('playwright');
const file = process.argv[2]; const b = await chromium.launch(); const ctx = await b.newContext(devices['iPhone 16']);
const pg = await ctx.newPage(); const errs = []; pg.on('pageerror', e => errs.push(e.message));
await pg.addInitScript(() => { window.claude = { use: () => Promise.reject(new Error('no')) }; });
await pg.goto('file://' + file + '#system'); await pg.waitForTimeout(2500);
const t = await pg.evaluate(() => document.querySelector('main').innerText);
const pass = (t.match(/\bPASS\b/g) || []).length, fail = (t.match(/\bFAIL\b/g) || []).length;
console.log('tab:', t.match(/Перевірки ядра[^\n]*/)?.[0], 'PASS', pass, 'FAIL', fail, 'errs', errs);
const ids = [...t.matchAll(/ID\n(\S+)\nПеревірка\n([^\n]+)\nРезультат\n([^\n]*)\n(PASS|FAIL)/g)].map(m => m[1] + ' ' + m[4] + ' — ' + m[2]);
console.log(ids.filter(x => /FAIL/.test(x)).join('\n') || 'no FAIL rows'); console.log(ids.length, 'rows; groups:', [...new Set(ids.map(x => x.replace(/\d+.*/, '')))].join(','));
await b.close();
